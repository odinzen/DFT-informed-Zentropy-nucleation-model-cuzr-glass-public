#!/usr/bin/env bash
# Runs the jobs in <run dir>/queue.txt one after another on the local cores, skipping any whose
# output already ends in JOB DONE, and copies each finished output to <copy dir>.
# Usage: bash dft_queue.sh <run dir> <copy dir> [ranks]
set -u
RUN=$1; COPY=$2; NP=${3:-10}
cd "$RUN"
mkdir -p "$COPY"
export OMP_NUM_THREADS=1
while read -r job; do
  [ -z "$job" ] && continue
  if grep -q "JOB DONE" "$job.out" 2>/dev/null; then echo "$(date '+%F %T') skip $job"; continue; fi
  echo "$(date '+%F %T') start $job"
  # crystals carry many k-points, so split them into pools; a Gamma-point liquid has one
  case "$job" in cryst_*) pools="-nk 5" ;; *) pools="" ;; esac
  # < /dev/null: mpirun reads stdin and would swallow the rest of queue.txt
  mpirun -np "$NP" --mca pml ob1 --mca btl self,sm pw.x $pools -in "$job.in" > "$job.out" 2>&1 < /dev/null
  status=$?
  rm -rf "tmp_$job"                     # wavefunction scratch, regenerated by any rerun
  cp "$job.out" "$COPY/"
  echo "$(date '+%F %T') end $job exit $status $(grep -a '^!' "$job.out" | tail -n 1)"
done < queue.txt
echo "$(date '+%F %T') QUEUE DONE"
